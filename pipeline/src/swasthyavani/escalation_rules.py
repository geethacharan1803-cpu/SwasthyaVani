_REFUSE_RE = [re.compile(p, re.IGNORECASE) for p in REFUSE_PATTERNS]


def is_danger_sign(text: str) -> bool:
    """Check if query matches any critical frontline danger sign."""
    return any(rx.search(text) for rx in _DANGER_RE)


def is_out_of_scope(text: str) -> bool:
    """Check if query is clinically out-of-scope (requiring doctor referral)."""
    return any(rx.search(text) for rx in _REFUSE_RE)


def route_danger_section(text: str) -> str:
    """Resolve the specific leaf section ID for an emergency danger sign."""
    for pattern, sec_id in ESC_LEAF_ROUTING:
        if re.search(pattern, text, re.IGNORECASE):
            return sec_id
    return "ESC-1.1"

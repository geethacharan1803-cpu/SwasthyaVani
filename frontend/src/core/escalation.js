/**
 * Check if query contains any danger sign requiring emergency escalation.
 * @param {string} text
 * @returns {boolean}
 */
export function detectDanger(text) {
  if (!text || typeof text !== 'string') return false;
  return DANGER_PATTERNS.some((rx) => rx.test(text));
}

/**
 * Route danger query to exact protocol leaf section.
 * @param {string} text
 * @returns {string}
 */
export function routeDangerLeaf(text) {
  if (!text) return 'ESC-1.1';
  for (const { pattern, secId } of ESC_LEAF_ROUTING) {
    if (pattern.test(text)) return secId;
  }
  return 'ESC-1.1';
}
